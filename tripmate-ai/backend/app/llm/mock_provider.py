"""
TripMate AI - Mock LLM Provider
Deterministic mock provider for unit testing, offline development, and CI environments.
Guarantees zero external network dependencies and explicitly flags all outputs as mock data.
"""

import inspect
import time
import uuid
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional, Type, TypeVar, get_args, get_origin
from pydantic import BaseModel
from pydantic.fields import FieldInfo

from app.llm.base import BaseLLMProvider
from app.llm.usage import LLMHealthStatus, LLMMessage, LLMResponse, TokenUsage
from app.schemas.tool import ToolCall
from app.utils.logger import get_logger

logger = get_logger(__name__)
T = TypeVar("T", bound=BaseModel)


class MockLLMProvider(BaseLLMProvider):
    """
    Mock LLM provider producing deterministic responses and mock Pydantic instances.
    """

    def __init__(self, model_name: str = "mock-gpt-4o") -> None:
        self.model_name = model_name
        self.provider_name = "mock"

    def get_provider_name(self) -> str:
        return self.provider_name

    def get_model_name(self) -> str:
        return self.model_name

    async def generate(
        self,
        messages: List[LLMMessage],
        temperature: float = 0.7,
        max_tokens: Optional[int] = None,
        **kwargs: Any,
    ) -> LLMResponse:
        """Emits deterministic mock text response based on user input."""
        start_time = time.perf_counter()

        last_user_prompt = ""
        for msg in reversed(messages):
            if msg.role == "user":
                last_user_prompt = msg.content
                break

        response_text = (
            f"[MOCK DATA - TripMate AI] Simulation response for model '{self.model_name}'. "
            f"Processed prompt snippet: '{last_user_prompt[:60]}...'. "
            "All recommendations and itineraries generated by this provider are test mocks."
        )

        latency_ms = (time.perf_counter() - start_time) * 1000.0
        prompt_tokens = sum(len(m.content.split()) for m in messages) * 2
        completion_tokens = len(response_text.split()) * 2

        usage = TokenUsage(
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=prompt_tokens + completion_tokens,
            estimated_cost_usd=TokenUsage.calculate_cost(
                self.model_name, prompt_tokens, completion_tokens
            ),
        )

        return LLMResponse(
            content=response_text,
            role="assistant",
            model=self.model_name,
            provider=self.provider_name,
            usage=usage,
            finish_reason="stop",
            latency_ms=round(latency_ms, 2),
            is_mock=True,
        )

    async def generate_with_tools(
        self,
        messages: List[LLMMessage],
        tools: List[Dict[str, Any]],
        temperature: float = 0.7,
        max_tokens: Optional[int] = None,
        **kwargs: Any,
    ) -> LLMResponse:
        """Simulates function calling decisions deterministically."""
        start_time = time.perf_counter()

        # Check if any message is a tool response (meaning tools have already executed)
        has_tool_results = any(m.role == "tool" for m in messages)

        # If tools have already executed or no tools supplied, formulate final response
        if has_tool_results or not tools:
            base_res = await self.generate(messages, temperature=temperature, max_tokens=max_tokens, **kwargs)
            return base_res

        # Otherwise, inspect last user message to pick realistic tool calls
        last_user_content = ""
        for m in reversed(messages):
            if m.role == "user":
                last_user_content = m.content
                break

        requested_tool_calls: List[ToolCall] = []
        available_tool_names = [
            t.get("function", {}).get("name") if "function" in t else t.get("name")
            for t in tools
        ]

        dest = "Jaipur"
        for candidate in ["goa", "jaipur", "tokyo", "paris", "delhi", "mumbai"]:
            if candidate in last_user_content.lower():
                dest = candidate.capitalize()
                break

        if "search_destination" in available_tool_names:
            requested_tool_calls.append(
                ToolCall(
                    id=f"call_{uuid.uuid4().hex[:8]}",
                    name="search_destination",
                    arguments={"destination": dest, "interests": ["culture", "sightseeing"]},
                )
            )

        if "get_weather" in available_tool_names:
            requested_tool_calls.append(
                ToolCall(
                    id=f"call_{uuid.uuid4().hex[:8]}",
                    name="get_weather",
                    arguments={"destination": dest},
                )
            )

        if "calculate_trip_budget" in available_tool_names:
            requested_tool_calls.append(
                ToolCall(
                    id=f"call_{uuid.uuid4().hex[:8]}",
                    name="calculate_trip_budget",
                    arguments={
                        "transportation": 3000.0,
                        "accommodation": 6000.0,
                        "food": 4000.0,
                        "activities": 2000.0,
                        "miscellaneous": 1000.0,
                        "currency": "INR",
                        "target_budget": 20000.0,
                        "days": 3,
                        "travelers": 2,
                    },
                )
            )

        if not requested_tool_calls and tools:
            first_name = available_tool_names[0]
            requested_tool_calls.append(
                ToolCall(
                    id=f"call_{uuid.uuid4().hex[:8]}",
                    name=first_name,
                    arguments={"destination": dest},
                )
            )

        latency_ms = (time.perf_counter() - start_time) * 1000.0
        return LLMResponse(
            content="[MOCK DATA] Requesting tool execution to assemble verified travel parameters.",
            role="assistant",
            model=self.model_name,
            provider=self.provider_name,
            usage=TokenUsage(prompt_tokens=40, completion_tokens=20, total_tokens=60),
            finish_reason="tool_calls",
            latency_ms=round(latency_ms, 2),
            is_mock=True,
            tool_calls=requested_tool_calls,
        )

    async def generate_structured(
        self,
        messages: List[LLMMessage],
        response_model: Type[T],
        temperature: float = 0.2,
        **kwargs: Any,
    ) -> T:
        """
        Dynamically generates a structurally valid mock instance of the requested Pydantic model.
        """
        mock_dict = self._create_mock_data_for_model(response_model)
        return response_model.model_validate(mock_dict)

    async def health_check(self) -> LLMHealthStatus:
        """Returns mock provider status confirming offline availability."""
        return LLMHealthStatus(
            is_available=True,
            provider=self.provider_name,
            model=self.model_name,
            is_mock=True,
            latency_ms=0.5,
            details={"mode": "offline_mock_mode", "status": "operational"},
        )

    def _create_mock_data_for_model(self, model_cls: Type[BaseModel]) -> Dict[str, Any]:
        """Recursively builds sample mock data adhering to the target Pydantic schema."""
        data: Dict[str, Any] = {}

        for field_name, field_info in model_cls.model_fields.items():
            if field_info.default_factory is not None:
                data[field_name] = field_info.default_factory()
            elif not field_info.is_required():
                data[field_name] = field_info.default
            else:
                data[field_name] = self._generate_value_for_type(
                    field_name, field_info.annotation
                )

        return data

    def _generate_value_for_type(self, field_name: str, annotation: Any) -> Any:
        """Synthesizes mock values for standard Python and Pydantic types."""
        origin = get_origin(annotation)
        args = get_args(annotation)

        # Handle Optional / Union types
        if origin is not None and type(None) in args:
            non_none_args = [arg for arg in args if arg is not type(None)]
            if non_none_args:
                return self._generate_value_for_type(field_name, non_none_args[0])
            return None

        # Handle List / Sequence
        if origin in (list, List):
            item_type = args[0] if args else str
            return [self._generate_value_for_type(field_name, item_type)]

        # Handle Dict
        if origin in (dict, Dict):
            val_type = args[1] if len(args) > 1 else str
            return {"mock_key": self._generate_value_for_type(field_name, val_type)}

        # Handle Literal
        if origin is not None and getattr(origin, "__name__", "") == "Literal":
            return args[0] if args else "mock_literal"

        # Handle nested BaseModel
        if inspect.isclass(annotation) and issubclass(annotation, BaseModel):
            return self._create_mock_data_for_model(annotation)

        # Handle Enum
        if inspect.isclass(annotation) and issubclass(annotation, Enum):
            return list(annotation)[0].value

        # Handle Primitives
        if annotation is str:
            if "destination" in field_name.lower():
                return "[MOCK] Jaipur, Rajasthan, India"
            if "currency" in field_name.lower():
                return "INR"
            return f"[MOCK] {field_name.replace('_', ' ').capitalize()}"
        elif annotation is int:
            if "days" in field_name.lower():
                return 3
            if "travelers" in field_name.lower():
                return 2
            return 10
        elif annotation is float:
            if "budget" in field_name.lower():
                return 25000.0
            return 100.0
        elif annotation is bool:
            return True
        elif annotation is datetime:
            return datetime.now(timezone.utc)

        return f"[MOCK] {field_name}"
