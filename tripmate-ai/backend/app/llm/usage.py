"""
TripMate AI - LLM Data Structures & Usage Tracking
Defines standard message wrappers, response payloads, token accounting,
and health status representations.
"""

from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field


class TokenUsage(BaseModel):
    """Token consumption accounting and approximate cost estimation."""

    prompt_tokens: int = Field(default=0, ge=0)
    completion_tokens: int = Field(default=0, ge=0)
    total_tokens: int = Field(default=0, ge=0)
    estimated_cost_usd: float = Field(default=0.0, ge=0.0)

    def add(self, other: "TokenUsage") -> "TokenUsage":
        """Accumulate token consumption from multiple turns or agent steps."""
        return TokenUsage(
            prompt_tokens=self.prompt_tokens + other.prompt_tokens,
            completion_tokens=self.completion_tokens + other.completion_tokens,
            total_tokens=self.total_tokens + other.total_tokens,
            estimated_cost_usd=round(self.estimated_cost_usd + other.estimated_cost_usd, 6),
        )

    @classmethod
    def calculate_cost(
        cls, model: str, prompt_tokens: int, completion_tokens: int
    ) -> float:
        """Calculate approximate USD cost based on standard model pricing."""
        # Indicative rates per 1M tokens ($/M)
        pricing = {
            "gpt-4o": {"input": 2.50, "output": 10.00},
            "gpt-4o-mini": {"input": 0.15, "output": 0.60},
            "gpt-4-turbo": {"input": 10.00, "output": 30.00},
            "gpt-3.5-turbo": {"input": 0.50, "output": 1.50},
        }
        rates = pricing.get(model.lower(), {"input": 0.0, "output": 0.0})
        cost = (prompt_tokens / 1_000_000 * rates["input"]) + (
            completion_tokens / 1_000_000 * rates["output"]
        )
        return round(cost, 6)


class LLMMessage(BaseModel):
    """Unified conversational message container."""

    role: Literal["system", "user", "assistant", "tool"] = Field(
        default="user", description="Participant role in the conversation"
    )
    content: str = Field(..., description="Message text or serialised payload")
    name: Optional[str] = Field(default=None, description="Optional agent or tool identifier")
    tool_call_id: Optional[str] = Field(
        default=None, description="Tool call correlation ID for tool role messages"
    )
    tool_calls: Optional[List[Dict[str, Any]]] = Field(
        default=None, description="Raw tool calls list if message is assistant tool request"
    )


from app.schemas.tool import ToolCall


class LLMResponse(BaseModel):
    """Unified response payload emitted by all provider implementations."""

    content: str = Field(..., description="Raw text generated by the model")
    role: str = Field(default="assistant")
    model: str = Field(..., description="Active model identity")
    provider: str = Field(..., description="Underlying provider name")
    usage: TokenUsage = Field(default_factory=TokenUsage)
    finish_reason: Optional[str] = Field(default="stop")
    latency_ms: float = Field(default=0.0, ge=0.0)
    is_mock: bool = Field(default=False)
    tool_calls: List[ToolCall] = Field(
        default_factory=list, description="Tool calls requested by the model"
    )


class LLMHealthStatus(BaseModel):
    """Health check outcome for an LLM provider."""

    is_available: bool = Field(..., description="Whether the provider is currently reachable and ready")
    provider: str = Field(..., description="Provider name (openai, ollama, mock)")
    model: str = Field(..., description="Configured model identifier")
    is_mock: bool = Field(default=False)
    latency_ms: Optional[float] = Field(default=None)
    error: Optional[str] = Field(default=None)
    details: Optional[Dict[str, Any]] = Field(default=None)

